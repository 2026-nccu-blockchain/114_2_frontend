export const getApiStatusMessage = (
  statusCode?: string,
  defaultMessage = '操作發生錯誤，請稍後再試',
) => {
  if (!statusCode) return defaultMessage;

  return apiStatusMessages[statusCode] || `${defaultMessage} (${statusCode})`;
};
